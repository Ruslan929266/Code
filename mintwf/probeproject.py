import turtle
t = turtle.Turtle()
t.speed(5)

t.penup()
t.pensize(5)
t.left(90)
t.forward(100)
t.left(90)
t.forward(100)
t.pendown()

t.color("black")
t.left(90)
t.forward(200)
t.circle(150, 180)
t.forward(200)
t.left(90)
t.forward(300)
t.penup()

def draw_wave():
    t.pensize(2)
    for _ in range(5):
        t.circle(17, 180)
        t.circle(-17, 180)

t.right(180)
t.forward(115)
t.right(90)
t.pendown()

t.begin_fill()
t.color("black","#0291D9")
t.right(90)
draw_wave()
t.penup()
t.goto(50, -250.00000000000006)
t.setheading(0)
t.pendown()
t.right(180)
t.circle(-150, 90)
t.forward(200)
t.right(90)
t.forward(100)
t.end_fill()

t.forward(200)
t.left(180)
t.begin_fill()
t.color("black","red")
t.forward(115)
draw_wave()
t.penup()
t.goto(50, -250.00000000000006)
t.setheading(0)
t.pendown()
t.circle(150, 90)
t.forward(200)
t.end_fill()

def draw_star():
    t.begin_fill()
    t.color("black","white")
    t.right(30)
    for i in range(6):
        t.forward(18)
        t.left(60)
        t.forward(20)
        t.right(120)
    t.end_fill()

t.left(90)
t.forward(230)
t.left(90)
t.penup()
t.forward(30)
t.pendown()
draw_star()
t.penup()
t.left(30)
t.forward(50)
t.right(90)
t.left(90)
t.forward(40)
t.pendown()
draw_star()
t.penup()
t.left(30)
t.forward(50)
t.right(90)
t.left(90)
t.forward(40)
t.pendown()
draw_star()

t.done()
